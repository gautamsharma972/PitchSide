def render(key: str, params: dict, lang: str = "en", style: str = "analyst") -> str:
    """Render a signal template. `style='fan'` prefers the `<key>_fan` wording when one exists."""
    lang = lang if lang in LANGS else "en"
    if style == "fan" and (key + "_fan") in P:
        key = key + "_fan"
    table = P.get(key)
    if not table:
        return ""
    tpl = table.get(lang) or table["en"]
    try:
        return tpl.format(**params)
    except (KeyError, IndexError):
        return tpl
